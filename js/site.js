  /* Boot                                                                */
  /* ------------------------------------------------------------------ */

  function boot() {
    if (PREVIEW) {
      initPreviewBridge();
      try {
        var draft = localStorage.getItem(DRAFT_KEY);
        if (draft) content = JSON.parse(draft);
      } catch (e) {}
    }

    var chrome = function () {
      if (PAGE === 'home') initHomeChrome();
      else if (PAGE === 'showcase' || PAGE === 'showcase2') initShowcaseChrome();
      else if (PAGE === 'reviews') initCosmicDecor();
    };

    fetch('content/content.json', { cache: 'no-cache' })
      .then(function (r) { return r.json(); })
      .then(function (json) {
        if (!content) content = json; /* preview draft wins */
        render();
        chrome();
        initTawk();
      })
      .catch(function (err) {
        console.error('[ElitexCMS] failed to load content.json:', err);
        if (content) { render(); chrome(); } else { hidePreloader(); }
      });

    /* safety: never trap users behind the preloader */
    setTimeout(hidePreloader, 4000);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
