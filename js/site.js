  function initSwiper() {
    if (typeof Swiper === 'undefined') return;
    if (swiperInstance) { try { swiperInstance.destroy(true, true); } catch (e) {} }
    swiperInstance = new Swiper('.testimonial-slider', {
      loop: true,
      autoplay: { delay: 5000, disableOnInteraction: false },
      pagination: { el: '.swiper-pagination', clickable: true },
      navigation: { nextEl: '.swiper-button-next', prevEl: '.swiper-button-prev' },
      breakpoints: {
        640: { slidesPerView: 1, spaceBetween: 20 },
        768: { slidesPerView: 2, spaceBetween: 30 },
        1024: { slidesPerView: 2, spaceBetween: 40 }
      }
    });
  }

  function bindVideoModal(grid) {
    var videoModal = $('#videoModal');
    var modalVideo = $('#modalVideo');
    if (!videoModal || !modalVideo) return;
    $$('.grid-item[data-video-src]', grid).forEach(function (item) {
      item.addEventListener('click', function () {
        modalVideo.src = item.getAttribute('data-video-src');
        videoModal.classList.add('active');
      });
    });
  }

