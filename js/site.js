  function render() {
    if (!content) return;
    try {
      applySeo();
      if (PAGE === 'home') { renderHome(); }
      else if (PAGE === 'showcase' || PAGE === 'showcase2') { renderShowcase(); }
      else if (PAGE === 'reviews') { renderReviews(); }
      initForms();
    } catch (err) {
      console.error('[ElitexCMS] render error:', err);
    }
    hidePreloader();
  }

